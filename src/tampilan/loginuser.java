    private void loginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginActionPerformed
        String nipInput = nip.getText().trim();
        String passInput = new String(pass.getPassword());

        if (nipInput.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Silakan masukkan NIP terlebih dahulu.", "Validasi Login", JOptionPane.WARNING_MESSAGE);
            nip.requestFocus();
            return;
        }
        if (passInput.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Silakan masukkan kata sandi terlebih dahulu.", "Validasi Login", JOptionPane.WARNING_MESSAGE);
            pass.requestFocus();
            return;
        }

        try {
            String sql = "SELECT * FROM users WHERE nip=? AND password=?";
            java.sql.Connection conn = new koneksi().getConnection();
            java.sql.PreparedStatement pst = conn.prepareStatement(sql);

            pst.setString(1, nipInput);
            pst.setString(2, passInput);

            java.sql.ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                String statusUser = rs.getString("status");
                String namaDariDB = rs.getString("nama");

                if (statusUser.equalsIgnoreCase("N")) {
                    JOptionPane.showMessageDialog(this, "Maaf, status akun Anda saat ini tidak aktif.", "Akses Ditolak", JOptionPane.WARNING_MESSAGE);
                    nip.setText("");
                    pass.setText("");
                    nip.requestFocus();
                } else {
                    GuruSession.clear();
                    UserSession.setNip(rs.getString("nip"));
                    UserSession.setLevel(rs.getString("lvl"));
                    UserSession.setNama(namaDariDB);
                    UserSession.setStatus(statusUser);

                    JOptionPane.showMessageDialog(this, "Login berhasil. Selamat datang, " + namaDariDB + "!");
                    new dashboardtu().setVisible(true);
                    this.dispose();
                }
            } else {
                JOptionPane.showMessageDialog(this, "NIP atau kata sandi tidak sesuai.", "Gagal Masuk", JOptionPane.ERROR_MESSAGE);
                pass.requestFocus();
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error koneksi: " + e.getMessage(), "Kesalahan Sistem", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_loginActionPerformed

